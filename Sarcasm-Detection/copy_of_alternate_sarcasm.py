def parse_conllu(conllu_str):
    """Extract tokens from a CoNLL-U formatted string into a single space-joined text.
    If conllu_str is blank or malformed, return empty string."""
    try:
        if not isinstance(conllu_str, str) or conllu_str.strip() == "":
            return ""
        lines = [l for l in conllu_str.splitlines() if l.strip() and not l.strip().startswith("#")]
        tokens = []
        for ln in lines:
            parts = ln.split("\t")
            # some CoNLL variations put index '.' or ranges; ensure index is numeric
            if len(parts) >= 2:
                tokens.append(parts[1])
        return " ".join(tokens)
    except Exception:
        return ""

