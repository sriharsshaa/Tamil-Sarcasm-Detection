def predict_tamil_headline(texts, encode_model=model, clf=mlp):
    """
    texts: single str or list[str] (Tamil text)
    returns: dict or list of dicts with predicted label and probability
    """
    single = False
    if isinstance(texts, str):
        texts = [texts]
        single = True
    emb = encode_model.encode([str(t) for t in texts], convert_to_numpy=True)
    emb = normalize(emb)
    preds = clf.predict(emb)
    probs = clf.predict_proba(emb)[:, 1] if hasattr(clf, "predict_proba") else None
    results = []
    for i, txt in enumerate(texts):
        results.append({
            "text": txt,
            "pred": int(preds[i]),
            "prob": float(probs[i]) if probs is not None else None
        })
    return results[0] if single else results

