class ResidualBlock(nn.Module):
    def __init__(self, dim, hidden_dim=None, dropout=DROPOUT):
        super().__init__()
        if hidden_dim is None:
            hidden_dim = dim
        self.fc1 = nn.Linear(dim, hidden_dim)
        self.bn1 = nn.BatchNorm1d(hidden_dim)
        self.act = nn.ReLU(inplace=True)
        self.drop = nn.Dropout(dropout)
        self.fc2 = nn.Linear(hidden_dim, dim)
        self.bn2 = nn.BatchNorm1d(dim)
        # If hidden_dim != dim, still allow residual via a projection
        if hidden_dim != dim:
            self.proj = nn.Linear(dim, dim)
        else:
            self.proj = None

    def forward(self, x):
        out = self.fc1(x)
        # bn1 expects (batch, feat) and fails when batch=1 with BatchNorm in eval? keep as is
        out = self.bn1(out)
        out = self.act(out)
        out = self.drop(out)
        out = self.fc2(out)
        out = self.bn2(out)
        if self.proj is not None:
            res = self.proj(x)
        else:
            res = x
        return self.act(out + res)

class ResidualMLP(nn.Module):
    def __init__(self, input_dim, hidden_dims=[512,256], n_blocks=2, dropout=DROPOUT):
        super().__init__()
        # initial projection to first hidden dim
        self.input_fc = nn.Linear(input_dim, hidden_dims[0])
        self.input_bn = nn.BatchNorm1d(hidden_dims[0])
        self.act = nn.ReLU(inplace=True)
        self.drop = nn.Dropout(dropout)

        # build several residual blocks (you can vary sizes)
        blocks = []
        # first block will have hidden_dim equal to hidden_dims[0]
        for i in range(len(hidden_dims)):
            dim = hidden_dims[i]
            # For block internal hidden dimension we choose dim // 2 if possible
            hid = max(dim // 2, 32)
            blocks.append(ResidualBlock(dim, hidden_dim=hid, dropout=dropout))
            # optionally add a transition linear to next dim if next exists
            if i + 1 < len(hidden_dims):
                next_dim = hidden_dims[i+1]
                blocks.append(nn.Linear(dim, next_dim))
                blocks.append(nn.BatchNorm1d(next_dim))
                blocks.append(nn.ReLU(inplace=True))
                blocks.append(nn.Dropout(dropout))

        self.blocks = nn.Sequential(*blocks)
        # final output head
        final_dim = hidden_dims[-1]
        self.head = nn.Sequential(
            nn.Linear(final_dim, final_dim//2),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(final_dim//2, 1)  # binary logit
        )

    def forward(self, x):
        # x: (B, input_dim)
        x = self.input_fc(x)
        x = self.input_bn(x)
        x = self.act(x)
        x = self.drop(x)
        x = self.blocks(x)
        x = self.head(x)
        return x  # logits (no sigmoid)

