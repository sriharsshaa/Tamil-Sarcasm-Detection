@torch.no_grad()
def evaluate(loader):
    model.eval()
    total = 0
    correct = 0
    losses = 0.0
    all_probs = []
    all_labels = []
    for xb, yb in loader:
        xb, yb = xb.to(DEVICE), yb.to(DEVICE)
        logits = model(xb)
        loss = criterion(logits, yb)
        losses += loss.item() * xb.size(0)
        probs = torch.softmax(logits, dim=1)[:,1]  # probability of class 1
        preds = probs >= 0.5
        correct += (preds.long() == yb).sum().item()
        total += xb.size(0)
        all_probs.append(probs.cpu().numpy())
        all_labels.append(yb.cpu().numpy())
    avg_loss = losses / total
    acc = correct / total
    probs = np.concatenate(all_probs) if len(all_probs)>0 else np.array([])
    labels = np.concatenate(all_labels) if len(all_labels)>0 else np.array([])
    try:
        roc = roc_auc_score(labels, probs)
    except Exception:
        roc = float("nan")
    return avg_loss, acc, roc, probs, labels

