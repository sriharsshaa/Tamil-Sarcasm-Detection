def binary_accuracy_from_logits(logits, labels):
    # logits: (B,1), labels: (B,1)
    probs = torch.sigmoid(logits)
    preds = (probs >= 0.5).float()
    correct = (preds == labels).float().sum()
    return (correct / labels.shape[0]).item()

@torch.no_grad()
def evaluate(model, dataloader, device=DEVICE):
    model.eval()
    running_loss = 0.0
    total = 0
    correct = 0
    all_logits = []
    for xb, yb in dataloader:
        xb = xb.to(device)
        yb = yb.to(device)
        logits = model(xb)
        loss = criterion(logits, yb)
        running_loss += loss.item() * xb.size(0)
        probs = torch.sigmoid(logits)
        preds = (probs >= 0.5).float()
        correct += (preds == yb).float().sum().item()
        total += xb.size(0)
        all_logits.append(logits.detach().cpu())
    avg_loss = running_loss / total
    acc = correct / total
    return avg_loss, acc

