class ResidualBlock(nn.Module):
    def __init__(self, dim, hidden_dim=None, dropout=0.3):
        super().__init__()
        if hidden_dim is None:
            hidden_dim = dim
        self.fc1 = nn.Linear(dim, hidden_dim)
        self.bn1 = nn.BatchNorm1d(hidden_dim)
        self.act = nn.ReLU(inplace=True)
        self.drop = nn.Dropout(dropout)
        self.fc2 = nn.Linear(hidden_dim, dim)
        self.bn2 = nn.BatchNorm1d(dim)
        # projection if dims differ (not used here usually)
        self.proj = None
        if hidden_dim != dim:
            self.proj = nn.Linear(dim, dim)

    def forward(self, x):
        out = self.fc1(x)
        out = self.bn1(out)
        out = self.act(out)
        out = self.drop(out)
        out = self.fc2(out)
        out = self.bn2(out)
        res = self.proj(x) if self.proj is not None else x
        return self.act(out + res)

class ResidualMLP(nn.Module):
    def __init__(self, input_dim, hidden_dims=[512, 256, 128], dropout=0.3):
        super().__init__()
        self.input_fc = nn.Linear(input_dim, hidden_dims[0])
        self.input_bn = nn.BatchNorm1d(hidden_dims[0])
        self.act = nn.ReLU(inplace=True)
        self.drop = nn.Dropout(dropout)

        blocks = []
        for i, dim in enumerate(hidden_dims):
            # residual blocks operate in block's dim
            blocks.append(ResidualBlock(dim, hidden_dim=max(dim//2, 64), dropout=dropout))
            if i + 1 < len(hidden_dims):
                # project to next dim
                next_dim = hidden_dims[i+1]
                blocks.append(nn.Linear(dim, next_dim))
                blocks.append(nn.BatchNorm1d(next_dim))
                blocks.append(nn.ReLU(inplace=True))
                blocks.append(nn.Dropout(dropout))
        self.blocks = nn.Sequential(*blocks)
        final_dim = hidden_dims[-1]
        self.head = nn.Sequential(
            nn.Linear(final_dim, max(final_dim//2, 64)),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(max(final_dim//2, 64), 2)  # 2 classes -> logits
        )

    def forward(self, x):
        x = self.input_fc(x)
        x = self.input_bn(x)
        x = self.act(x)
        x = self.drop(x)
        x = self.blocks(x)
        x = self.head(x)
        return x

